// Precompute, per cut and refractive index, the best pavilion/crown angles and the maximum light
// performance a perfect cutter can reach. The game grades every stone relative to this ceiling, so
// "100% brilliance" means you found the true optical optimum for that material.
// Usage: node tools/optics-table.mjs   → writes src/optable.js
import fs from 'node:fs';
import { CUTS, cutPlanes, outlineOf } from '../src/cuts.js';
import { analyze, perf } from '../src/optics.js';
const RIS = [1.45, 1.55, 1.65, 1.75, 1.85, 2.0, 2.2, 2.42];
const out = {};
const ev = (id, ri, pav, crown) => { const C = CUTS[id], o = outlineOf(id); const pl = cutPlanes(id, { pav, crown, table: C.table, uG: 1, uP: 1, uC: 1, uT: 1 }); return perf(analyze(pl, null, { ri, disp: 0.02, grid: 16, bx: 1, bz: o.halfW })); };
for (const id of Object.keys(CUTS)) {
  out[id] = [];
  for (const ri of RIS) {
    let best = { s: -1 };
    for (let pav = 32; pav <= 56; pav += 1.5) for (let crown = 24; crown <= 44; crown += 2.5) { const s = ev(id, ri, pav, crown); if (s > best.s) best = { s, pav, crown }; }
    const b0 = best; for (let pav = b0.pav - 1.5; pav <= b0.pav + 1.5; pav += 0.5) for (let crown = Math.max(24, b0.crown - 2); crown <= Math.min(44, b0.crown + 2); crown += 1) { const s = ev(id, ri, pav, crown); if (s > best.s) best = { s, pav, crown }; }
    out[id].push([ri, +best.pav.toFixed(1), +best.crown.toFixed(1), +best.s.toFixed(3)]);
    process.stdout.write(`${id} ri ${ri}: pav ${best.pav} crown ${best.crown} perf ${best.s.toFixed(3)}\n`);
  }
}
fs.writeFileSync(new URL('../src/optable.js', import.meta.url), `// generated by tools/optics-table.mjs: [ri, best pavilion°, best crown°, max performance] per cut\nexport const OPTABLE = ${JSON.stringify(out)};\n`);
